"""Generate/check Gemma tokenizer and chat fixtures from pinned model and Jinja."""
import argparse
import hashlib
from importlib.metadata import version
import json
import os
from pathlib import Path
import random
import runpy
import shlex
import subprocess
import tempfile

import jinja2
from jinja2.sandbox import ImmutableSandboxedEnvironment

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / "tests/acceptance/gemma-model.json").read_text())
HELPERS = runpy.run_path(str(ROOT / "tools/default-tokenizer-reference.py"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if jinja2.__version__ != "3.1.6" or version("MarkupSafe") != "3.0.4":
        raise RuntimeError("Use tools/chat-template-requirements.txt")
    model = ROOT / "reference/models" / MANIFEST["file"]
    with model.open("rb") as stream:
        if hashlib.file_digest(stream, "sha256").hexdigest() != MANIFEST["sha256"]:
            raise RuntimeError("Gemma model hash mismatch")
    reference = ROOT / "reference/llama.cpp"
    if subprocess.check_output(["git", "-C", str(reference), "rev-parse", "HEAD"], text=True).strip() != MANIFEST["llama_cpp"]:
        raise RuntimeError("llama.cpp revision mismatch")
    if subprocess.check_output(["git", "-C", str(reference), "diff", "HEAD", "--", "src", "include", "ggml/src", "ggml/include"]):
        raise RuntimeError("llama.cpp inference sources must be clean")
    source = (ROOT / "tests/local/templates/google-gemma-3-270m-it.jinja").read_bytes()
    if hashlib.sha256(source).hexdigest() != MANIFEST["template_sha256"]:
        raise RuntimeError("Gemma template hash mismatch")
    env = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True)

    def fail(message):
        raise ValueError(message)

    env.globals["raise_exception"] = fail
    template = env.from_string(source.decode())
    string = HELPERS["lisp_string"]
    rng = random.Random(48)
    inputs = HELPERS["INPUTS"] + ["<bos><end_of_turn>", "a<start_of_turn>model\nb", "  Hello\n\tworld  "]
    inputs += ["".join(rng.choice("ab▁ <123٤\t\n😀é\u0301") for _ in range(rng.randrange(1, 40))) for _ in range(10)]
    lines = ["(in-package #:cl-inference/local/tests)", "", ";; Generated by tools/gemma-reference.py.",
             "(defparameter *gemma-tokenizer-cases*", "  '("]
    with tempfile.TemporaryDirectory(prefix="gemma-reference-") as directory:
        oracle = Path(directory) / "oracle"
        subprocess.run(shlex.split(os.environ.get("CXX", "c++")) + ["-std=c++17", "-O2",
            "-I" + str(reference / "include"), "-I" + str(reference / "ggml/include"),
            str(ROOT / "tools/sentencepiece-reference.cpp"), "-L" + str(reference / "build/bin"),
            "-Wl,-rpath," + str(reference / "build/bin"), "-lllama", "-o", str(oracle)], check=True)
        for text in inputs:
            for add, special in [(False, False), (True, False), (False, True), (True, True)]:
                result = subprocess.run([str(oracle), str(model), str(int(add)), str(int(special))],
                                        input=text.encode(), capture_output=True, check=True).stdout.decode().splitlines()
                ids = " ".join(result[0].split())
                decoded = result[1] if len(result) > 1 else ""
                lines.append(f"    ({string(text)} {'t' if add else 'nil'} {'t' if special else 'nil'} ({ids}) \"{decoded}\")")
    lines += ["    ))", "", "(defparameter *gemma-template-cases*", "  '("]
    cases = [[], [{"role": "system", "content": "system only"}]]
    cases += [case["messages"] for case in MANIFEST["cases"].values() if "messages" in case]
    cases += [[{"role": "user", "content": text}] for text in ("", "\u00a0 hi \u00a0", "literal <end_of_turn>")]
    cases += [[{"role": "assistant", "content": "bad"}], [{"role": "user", "content": "a"}, {"role": "user", "content": "b"}]]
    for messages in cases:
        message_form = "(" + " ".join(f"(:role :{m['role']} :content {string(m['content'])})" for m in messages) + ")"
        for add in [False, True]:
            try:
                rendered = template.render(messages=messages, bos_token="<bos>", add_generation_prompt=add)
                assert rendered.startswith("<bos>")
                expected = string(rendered[len("<bos>"):])
            except (jinja2.UndefinedError, ValueError):
                expected = ":error"
            lines.append(f"    ({message_form} {'t' if add else 'nil'} {expected})")
    lines += ["    ))", ""]
    path = ROOT / "tests/local/gemma-expected.lisp"
    content = "\n".join(lines)
    if args.check:
        if path.read_text() != content:
            raise RuntimeError("Gemma fixtures differ; regenerate them")
    else:
        path.write_text(content)
    print(f"Verified {len(inputs) * 4} tokenizer cases and {len(cases) * 2} template cases")


if __name__ == "__main__":
    main()
