"""Generate or check Qwen3.5 splits, IDs and decoded bytes from pinned llama.cpp."""
import argparse
import hashlib
import os
from pathlib import Path
import random
import runpy
import shlex
import struct
import subprocess
import tempfile

HELPERS = runpy.run_path(str(Path(__file__).with_name("default-tokenizer-reference.py")))
INPUTS, REVISION, lisp_string, run, byte_chars = (HELPERS[key] for key in
    ("INPUTS", "REVISION", "lisp_string", "run", "byte_chars"))
ROOT = Path(__file__).resolve().parents[1]
VOCAB_SHA256 = "63ed952ff338996cf0bdf24a7b10015124273f75c6dc9bb427356aa3f67ec62c"
CHARS = byte_chars()
TOKENS = CHARS + ["<s>", "</s>", "<think>"]
TYPES = [1] * 256 + [3, 3, 4]
MERGES = []
for text in ["hello", "e\u0301", "\u0301a", "a\u0903", "a\u20dd", "a\U0001d165", "!\u0301a", "ab"]:
    encoded = "".join(CHARS[b] for b in text.encode())
    left = encoded[0]
    for right in encoded[1:]:
        merged = left + right
        if merged not in TOKENS:
            MERGES.append(left + " " + right)
            TOKENS.append(merged)
            TYPES.append(1)
        left = merged


def write_vocab(path):
    metadata = [
        ("general.architecture", 8, "llama"), ("tokenizer.ggml.model", 8, "gpt2"),
        ("tokenizer.ggml.pre", 8, "qwen35"),
        ("tokenizer.ggml.tokens", 9, (8, TOKENS)),
        ("tokenizer.ggml.token_type", 9, (5, TYPES)),
        ("tokenizer.ggml.merges", 9, (8, MERGES)),
        ("tokenizer.ggml.bos_token_id", 4, 256), ("tokenizer.ggml.eos_token_id", 4, 257),
    ]

    def value(kind, item):
        if kind == 8:
            data = item.encode()
            return struct.pack("<Q", len(data)) + data
        if kind == 9:
            subtype, items = item
            return struct.pack("<IQ", subtype, len(items)) + b"".join(value(subtype, x) for x in items)
        return struct.pack({4: "<I", 5: "<i"}[kind], item)

    data = struct.pack("<IIQQ", 0x46554747, 3, 0, len(metadata))
    for key, kind, item in metadata:
        data += value(8, key) + struct.pack("<I", kind) + value(kind, item)
    path.write_bytes(data + bytes((-len(data)) % 32))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", type=Path, default=ROOT / "reference/llama.cpp")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ref = args.reference.resolve()
    if run(["git", "-C", str(ref), "rev-parse", "HEAD"], text=True).strip() != REVISION:
        raise RuntimeError("Reference revision must be " + REVISION)
    if run(["git", "-C", str(ref), "diff", "HEAD", "--", "src", "include", "ggml/src", "ggml/include"]):
        raise RuntimeError("Reference tokenizer sources must be clean")
    version = subprocess.run([str(ref / "build/bin/llama-tokenize"), "--version"],
                             check=True, capture_output=True, text=True)
    if REVISION[:7] not in version.stdout + version.stderr:
        raise RuntimeError("Rebuild llama.cpp at " + REVISION)
    vocab = ref / "models/ggml-vocab-qwen35.gguf"
    if hashlib.sha256(vocab.read_bytes()).hexdigest() != VOCAB_SHA256:
        raise RuntimeError("Reference vocabulary checksum mismatch")
    inputs = INPUTS + [
        "\u0301", "\u0301\u0308", "\u0903", "\u20dd", "\U0001d165", "e\u0301", "é",
        "\u0301a", "a\u0903", "a\u20dd", "a\U0001d165", "!\u0301a", "!!\u0301a",
        " \u0301", "\n\u0301", "1\u0301a", "\u03011", "\u0301!", "a\u0301\u0308b",
        "हिन्दी বাংলা தமிழ்", "العَرَبِيَّة", "שָׁלוֹם", "ก้ 中文", "\u0301<s>\u0308",
        "e\u0301<think>a\u0903", "<s><s>e\u0301</s>", "<think><think>",
        "<|im_start|>e\u0301<|im_end|>", "\u0301<|endoftext|>\u0903",
        "<|im_start|><|im_start|>\u0301<|im_end|>", "<think>e\u0301</think>",
        " \t<|im_end|>\n\u0301", "\u0301<|im_end|>\u20dd<|im_start|>a",
    ]
    rng = random.Random(60)
    inputs += ["".join(rng.choice("ab 'S_+$`123٤²\t\n\r😀é\u0301\u0903\u20dd\U0001d165")
                       for _ in range(rng.randrange(1, 65))) for _ in range(100)]
    lines = ["(in-package #:cl-inference/local/tests)", "",
             ";;; Generated by tools/qwen35-reference.py; do not edit.",
             f";;; llama.cpp {REVISION}; vocabulary SHA256 {VOCAB_SHA256}.", "",
             "(defparameter *qwen35-reference-tokens* '(" + " ".join(map(lisp_string, TOKENS)) + "))",
             "(defparameter *qwen35-reference-types* '(" + " ".join(map(str, TYPES)) + "))",
             "(defparameter *qwen35-reference-merges* '(" + " ".join(map(lisp_string, MERGES)) + "))",
             "", "(defparameter *qwen35-reference-splits*", "  '("]
    cases = []
    with tempfile.TemporaryDirectory(prefix="qwen35-reference-") as directory:
        tmp = Path(directory)
        oracle = tmp / "oracle"
        run(shlex.split(os.environ.get("CXX", "c++")) + [
            "-std=c++17", "-O2", "-I" + str(ref / "include"), "-I" + str(ref / "ggml/include"),
            "-I" + str(ref / "src"), str(ROOT / "tools/qwen35-reference.cpp"),
            str(ref / "src/unicode.cpp"), str(ref / "src/unicode-data.cpp"),
            "-L" + str(ref / "build/bin"), "-Wl,-rpath," + str(ref / "build/bin"),
            "-lllama", "-o", str(oracle)])
        synthetic = tmp / "synthetic.gguf"
        write_vocab(synthetic)
        for text in inputs:
            pieces = [bytes.fromhex(line).decode() for line in
                      run([str(oracle), "--split"], input=text.encode()).decode().splitlines()]
            assert "".join(pieces) == text
            lines.append("    (" + lisp_string(text) + " (" + " ".join(map(lisp_string, pieces)) + "))")
        combinations = [(add, special) for add in (False, True) for special in (False, True)]
        requests = [(text, add, special) for text in inputs for add, special in combinations]
        payload = "".join(f"{int(add)} {int(special)} {text.encode().hex()}\n"
                          for text, add, special in requests).encode()
        for name, path in [("synthetic", synthetic), ("vocab", vocab)]:
            result = run([str(oracle), str(path)], input=payload).decode().splitlines()
            if len(result) != len(requests) * 2:
                raise RuntimeError("Incomplete tokenizer oracle output")
            for i, (text, add, special) in enumerate(requests):
                ids = " ".join(result[2 * i].split())
                hex_bytes = result[2 * i + 1]
                cases.append(f"    (:{name} {lisp_string(text)} {'t' if add else 'nil'} "
                             f"{'t' if special else 'nil'} ({ids}) \"{hex_bytes}\")")
    lines += ["    ))", "", "(defparameter *qwen35-reference-cases*", "  '("] + cases + ["    ))", ""]
    expected = "\n".join(lines)
    target = ROOT / "tests/local/qwen35-expected.lisp"
    if args.check:
        if target.read_text() != expected:
            raise RuntimeError("Qwen3.5 expectations differ; regenerate and review")
    else:
        target.write_text(expected)
    print(f"Verified {len(inputs)} split cases and {len(cases)} tokenizer cases")


if __name__ == "__main__":
    main()
